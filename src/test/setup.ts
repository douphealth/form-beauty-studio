import "@testing-library/jest-dom";

// Shared by DOM tests (jsdom) and the Node-environment Worker tests, so the
// browser polyfill only applies when a window exists.
if (typeof window !== "undefined") {
  Object.defineProperty(window, "matchMedia", {
    writable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => {},
    }),
  });
}
